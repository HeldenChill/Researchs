// Rung 0: arithmetic on a config. Rates are per tick.
import {mkdirSync, writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {PLACEHOLDER_CONFIG, WALK_SPEED} from './config.ts';
import type {Config} from './types.ts';

export type Verdict = 'incapable' | 'starve' | 'overload' | 'ok';
export type Sheet = {demand: number; supply: number; pit: number; haul: number; haulCycleTicks: number; verdict: Verdict};

export function sheet(c: Config): Sheet {
  const percent = c.food.mass >= c.carry.heavyMassFrom ? c.carry.heavyPercent : c.carry.lightPercent;
  // Walk back empty, pick up, carry, drop.
  const haulCycleTicks = c.walkTicks + 1 + Math.ceil((c.walkTicks * WALK_SPEED) / percent) + 1;
  const demand = c.drainPerTick / c.food.yieldHunger;
  const supply = 1 / c.intake.meanGapTicks;
  const pit = Math.floor(c.acidCapacity / c.food.size) / c.food.digestTicks;
  const haul = c.crewCount / haulCycleTicks;
  const capacity = Math.min(pit, haul);
  const verdict = capacity < demand ? 'incapable' : supply < demand ? 'starve' : supply > capacity ? 'overload' : 'ok';
  return {demand, supply, pit, haul, haulCycleTicks, verdict};
}

export const GRID = {
  meanGap: [20, 30, 40, 50, 60, 70, 80, 100, 120],
  walk: [20, 40, 60],
  capacity: [1, 2, 3],
  crew: [3, 4],
};

export function primaryGrid(base: Config): Config[] {
  return GRID.crew.flatMap(crewCount =>
    GRID.capacity.flatMap(acidCapacity =>
      GRID.walk.flatMap(walkTicks =>
        GRID.meanGap.map(meanGapTicks => ({
          ...base,
          crewCount,
          acidCapacity,
          walkTicks,
          intake: {...base.intake, meanGapTicks, jitterTicks: Math.floor(meanGapTicks / 3)},
        })),
      ),
    ),
  );
}

export function renderSheet(base: Config): string {
  const s = sheet(base);
  const per100 = (rate: number) => (rate * 100).toFixed(2);
  const inputs: [string, number, string][] = [
    ['crewCount', base.crewCount, 'PLACEHOLDER'],
    ['walkTicks', base.walkTicks, 'PLACEHOLDER'],
    ['acidCapacity', base.acidCapacity, 'PLACEHOLDER'],
    ['drainPerTick', base.drainPerTick, 'PLACEHOLDER'],
    ['food.mass', base.food.mass, 'PLACEHOLDER'],
    ['food.size', base.food.size, 'PLACEHOLDER'],
    ['food.digestTicks', base.food.digestTicks, 'PLACEHOLDER'],
    ['food.yieldHunger', base.food.yieldHunger, 'PLACEHOLDER'],
    ['carry.heavyMassFrom', base.carry.heavyMassFrom, 'PLACEHOLDER'],
    ['carry.lightPercent', base.carry.lightPercent, 'PLACEHOLDER'],
    ['carry.heavyPercent', base.carry.heavyPercent, 'SOURCE (solo heavy carry)'],
    ['intake.meanGapTicks', base.intake.meanGapTicks, 'PLACEHOLDER'],
  ];

  const grid = primaryGrid(base).map(c => ({c, verdict: sheet(c).verdict}));
  const verdicts: Verdict[] = ['ok', 'starve', 'overload', 'incapable'];
  const count = (v: Verdict) => grid.filter(g => g.verdict === v).length;
  const pass = count('ok') > 0 && count('ok') < grid.length;

  // One table per crew and capacity: rows are walk times, columns are arrival gaps.
  const tables = GRID.crew.flatMap(crew =>
    GRID.capacity.map(capacity => {
      const rows = GRID.walk.map(walk => {
        const cells = GRID.meanGap.map(gap => grid.find(g => g.c.crewCount === crew && g.c.acidCapacity === capacity
          && g.c.walkTicks === walk && g.c.intake.meanGapTicks === gap)!.verdict);
        return `| ${walk} | ${cells.join(' | ')} |`;
      });
      return [`### Crew ${crew}, capacity ${capacity}`, '',
        `| walk \\ gap | ${GRID.meanGap.join(' | ')} |`, `|---|${'---|'.repeat(GRID.meanGap.length)}`, ...rows, ''].join('\n');
    }),
  );

  // The small offset stops floating division from rounding a whole tick the wrong way.
  const shortestOk = Math.ceil(1 / Math.min(s.pit, s.haul) - 1e-9);
  const longestOk = Math.floor(1 / s.demand + 1e-9);

  return [
    '# Rung 0: numbers sheet',
    '',
    'Generated by `node src/numbers.ts`. Arithmetic only. Ten ticks are one second.',
    '',
    '## Inputs', '', '| Input | Value | Label |', '|---|---|---|',
    ...inputs.map(([name, value, label]) => `| ${name} | ${value} | ${label} |`),
    '',
    '## Base point', '', '| Rate, items per 100 ticks | Value |', '|---|---|',
    `| Food the worm needs (demand) | ${per100(s.demand)} |`,
    `| Food that arrives (supply) | ${per100(s.supply)} |`,
    `| Pit can digest | ${per100(s.pit)} |`,
    `| Crew can haul | ${per100(s.haul)} |`,
    '',
    `Haul cycle: ${s.haulCycleTicks} ticks. Verdict: **${s.verdict}**.`,
    s.verdict === 'incapable'
      ? 'No arrival gap is ok with the other base values.'
      : `With the other base values, an arrival gap from ${shortestOk} to ${longestOk} ticks is ok.`,
    '',
    '## Primary grid', '', '| Verdict | Points |', '|---|---|',
    ...verdicts.map(v => `| ${v} | ${count(v)} |`),
    '',
    `**Rung 0 pass condition: ${pass ? 'PASS' : 'FAIL'}** (at least one ok point and at least one not ok, out of ${grid.length}).`,
    '',
    ...tables,
    '## Limits', '',
    '- Ignores time spent sealing breaches.',
    '- Ignores hunger wasted at the maximum.',
    '- Ignores random arrival gaps.',
    '- `ok` is a necessary-condition estimate. It does not predict the simulation.',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = new URL('../results/rung0.md', import.meta.url);
  mkdirSync(new URL('.', out), {recursive: true});
  writeFileSync(out, renderSheet(PLACEHOLDER_CONFIG));
  console.log('wrote results/rung0.md');
}
